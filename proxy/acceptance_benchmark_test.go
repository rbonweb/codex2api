// proxy/acceptance_benchmark_test.go
//
// End-to-end performance and resource gate acceptance tests for Spec §9.3 scenarios 24~28.
//
// Scenario 24: the same real HTTP streaming pipeline with guard on and off, 5 groups each, where the client actually receives valid
// delta; first valid TTFT P95 increase <= 10ms, process CPU increase <= 20%, and baseline
// CPU must be positive (<= 0 is treated as an invalid experiment and FAILs immediately).
// Scenario 25: the CPU median of the three parts envelope/scan/snapshot at 1/2/4 MiB, for each doubling
// ratio <= 2.5, and the real guard must not be falsely triggered by non-periodic PRNG data.
// Scenario 26: a single channel's live state reference <= 64KiB; the long-run gate (default 3s smoke, set
// RUN_OUTPUTGUARD_LONG_RUN=1 runs for 10 minutes) automatically judges goroutine/FD/heap growth.
// Scenario 27: the 4096-count limit for extremely fine 1~4B deltas, with the request event budget running out before the byte budget,
// quantitative verification, plus the combination of interleaved multi-tool calls and long thinking.
// Scenario 28: the real error/log redaction boundary; the internal reason, public responses and terminal envelope
// must never echo the model's original text or credentials.
package proxy

